"""Render fail2ban filter/jail files from the ``classify`` catalogue.

Generating the filters from the same patterns used for the analysis
keeps the deployed rules and the backtested rules identical. All
regexes stay RE2-compatible so the backtester can run them in DuckDB.
"""

import configparser
import textwrap
from pathlib import Path

from analysis import classify

FILTER_DIRNAME = 'filter.d'
JAIL_FILENAME = 'jail.local.example'
FAIL2BAN_DIR = Path(__file__).parent / 'fail2ban'
HOST_TAG = '<HOST>'
COMMENT_WIDTH = 77
# Matches the start of a combined-format line up to the request method.
LINE_START = r'^<HOST> \S+ \S+ \[[^\]]*\] "[A-Za-z]+ '
# nginx escapes non-printable request bytes as \xNN.
MALFORMED_REQUEST = r'^<HOST> \S+ \S+ \[[^\]]*\] "(?:\\x[0-9A-Fa-f]{2})+'
NGINX_FILTER_HEADER = (
    '# Generated by `python spam_analysis.py filters` from '
    'analysis/classify.py.\n# Do not edit by hand.\n')

# Explains each jail's trigger; galaxy-scan's is built from classify.
MALFORMED_DESCRIPTION = (
    'Requests whose request line is not valid HTTP: raw bytes that nginx '
    'logs as \\xNN escapes, such as TLS handshakes sent to the plain-HTTP '
    'port by port scanners.')
BADAGENT_DESCRIPTION = (
    'Requests whose User-Agent is a known attack/scanning tool '
    '(zgrab, masscan, nmap, nuclei, sqlmap, ...). Generic HTTP libraries '
    '(python-requests, curl, httpx) are deliberately NOT matched: they are '
    'legitimate API clients.')
SCAN_PREAMBLE = (
    'Requests for paths that Galaxy never serves, in any HTTP method and '
    'with any response status (except where noted). One failregex line '
    'per category, in this order:')
SCAN_NOT_MATCHED = (
    'Not matched on purpose: /api/* paths that merely look unfamiliar. '
    'That needs a list of real Galaxy routes which goes stale; only '
    'scanner signatures are matched, including inside /api/ '
    '(e.g. /api/.env).')

# name -> (filter name, maxretry, findtime seconds, bantime seconds)
JAILS = {
    'galaxy-scan': (3, 600, 86400),
    'galaxy-malformed': (3, 600, 3600),
    'galaxy-badagent': (1, 600, 86400),
}
IGNORE_IP = '127.0.0.0/8 ::1'


def scoped_flags(pattern: str) -> str:
    """Turn a leading ``(?i)`` into a scoped ``(?i:...)`` group.

    Python (fail2ban) rejects global flags that aren't at the very start
    of the final expression, so a prefix would break them.
    """
    if pattern.startswith('(?i)'):
        return f'(?i:{pattern[4:]})'
    return pattern


def target_regex(pattern: str, status: str = r'\d{3}') -> str:
    """Regex for a request line whose target matches ``pattern``.

    A ``$`` in the catalogue means "end of target", which in a raw log
    line is the space before the protocol, so it becomes a space.
    """
    body = scoped_flags(pattern).replace('$', ' ')
    if body.startswith('(?i:^/') or body.startswith('^/'):
        # Anchored at the start of the target.
        return f'{LINE_START}{body.replace("^/", "/", 1)}.*" {status}'
    return f'{LINE_START}\\S*{body}.*" {status}'


def scan_failregex() -> list[str]:
    # bogus_api is deliberately absent: it needs a Galaxy route
    # allowlist and misfires on client bugs such as /api/api/....
    return (
        [target_regex(p) for p in classify.SCANNER_PATH_PATTERNS.values()]
        + [target_regex(p, status=r'4\d\d')
           for p in classify.SCANNER_4XX_PATTERNS.values()])


def badagent_failregex() -> list[str]:
    ua = scoped_flags(classify.TOOL_UA_PATTERNS)
    return [
        r'^<HOST> \S+ \S+ \[[^\]]*\] "[^"]*" \d{3} \S+ "[^"]*" '
        rf'"[^"]*{ua}[^"]*"$'
    ]


def definitions() -> dict[str, tuple[list[str], list[str]]]:
    """Jail name -> (failregex list, ignoreregex list)."""
    return {
        'galaxy-scan': (scan_failregex(), []),
        'galaxy-malformed': ([MALFORMED_REQUEST], []),
        'galaxy-badagent': (badagent_failregex(), []),
    }


def _wrap(text: str, **kwargs) -> list[str]:
    return textwrap.wrap(
        text, COMMENT_WIDTH, break_on_hyphens=False, **kwargs) or ['']


def _comment(text: str) -> str:
    """Render ``text`` as comment lines.

    Plain lines are wrapped to COMMENT_WIDTH; indented lines (list items,
    already wrapped by the caller) are left as they are.
    """
    out = []
    for line in text.split('\n'):
        wrapped = [line] if line.startswith(' ') else _wrap(line)
        out.extend(f'# {w}'.rstrip() for w in wrapped)
    return '\n'.join(out) + '\n'


def scan_description() -> str:
    names = [
        *classify.SCANNER_PATH_PATTERNS, *classify.SCANNER_4XX_PATTERNS]
    name_width = max(len(n) for n in names)
    num_width = len(str(len(names)))
    lines = []
    for i, name in enumerate(names, 1):
        head = f'  {str(i).rjust(num_width)}. {name.ljust(name_width)}  '
        lines.extend(_wrap(
            head + classify.SCANNER_DESCRIPTIONS[name],
            subsequent_indent=' ' * len(head)))
    return '\n'.join([SCAN_PREAMBLE, *lines, '', SCAN_NOT_MATCHED])


def descriptions() -> dict[str, str]:
    return {
        'galaxy-scan': scan_description(),
        'galaxy-malformed': MALFORMED_DESCRIPTION,
        'galaxy-badagent': BADAGENT_DESCRIPTION,
    }


def render_filter(
    failregex: list[str],
    ignoreregex: list[str],
    description: str = '',
) -> str:
    def block(key: str, regexes: list[str]) -> str:
        if not regexes:
            return f'{key} =\n'
        # fail2ban reads config with %-interpolation, so a literal % (as
        # in the URL-encoded %2e patterns) must be written as %%.
        joined = '\n            '.join(r.replace('%', '%%') for r in regexes)
        return f'{key} = {joined}\n'

    about = _comment(description) + '#\n' if description else ''
    return (
        NGINX_FILTER_HEADER + '#\n' + about + '\n[Definition]\n'
        + block('failregex', failregex)
        + block('ignoreregex', ignoreregex))


def render_jail() -> str:
    parts = [
        '# Example jails; tune with `python spam_analysis.py backtest`.\n'
        '# Add the IPs from allowlist_candidates.csv to ignoreip.\n'
        '# 127.0.0.0/8 MUST be ignored: interactive-tool traffic reaches\n'
        '# nginx via a local proxy, so banning loopback breaks them.\n'
    ]
    for name, (maxretry, findtime, bantime) in JAILS.items():
        parts.append(
            f'\n[{name}]\nenabled  = true\nport     = http,https\n'
            f'filter   = {name}\nlogpath  = /var/log/nginx/access.log\n'
            f'maxretry = {maxretry}\nfindtime = {findtime}\n'
            f'bantime  = {bantime}\nignoreip = {IGNORE_IP}\n')
    return ''.join(parts)


def write_all(out_dir: Path = FAIL2BAN_DIR) -> list[Path]:
    filter_dir = out_dir / FILTER_DIRNAME
    filter_dir.mkdir(parents=True, exist_ok=True)
    written = []
    about = descriptions()
    for name, (fail, ignore) in definitions().items():
        path = filter_dir / f'{name}.conf'
        path.write_text(render_filter(fail, ignore, about[name]))
        written.append(path)
    jail = out_dir / JAIL_FILENAME
    jail.write_text(render_jail())
    written.append(jail)
    return written


def stale_files(out_dir: Path = FAIL2BAN_DIR) -> list[Path]:
    """Files on disk that differ from what the catalogue generates."""
    expected = {}
    about = descriptions()
    for name, (fail, ignore) in definitions().items():
        expected[out_dir / FILTER_DIRNAME / f'{name}.conf'] = (
            render_filter(fail, ignore, about[name]))
    expected[out_dir / JAIL_FILENAME] = render_jail()
    return [
        path for path, text in expected.items()
        if not path.exists() or path.read_text() != text
    ]


def load_filter(path: Path) -> tuple[list[str], list[str]]:
    """Read failregex/ignoreregex back from a filter .conf file.

    Uses %-interpolation exactly like fail2ban, so a filter that fail2ban
    can't load fails here too (and %% decodes back to %).
    """
    parser = configparser.ConfigParser(
        interpolation=configparser.BasicInterpolation())
    parser.read(path)
    section = parser['Definition']

    def lines(key: str) -> list[str]:
        return [x.strip() for x in section.get(key, '').splitlines()
                if x.strip()]

    return lines('failregex'), lines('ignoreregex')


def load_jails(path: Path) -> dict[str, dict]:
    parser = configparser.RawConfigParser()
    parser.read(path)
    return {
        name: {
            'maxretry': parser.getint(name, 'maxretry'),
            'findtime': parser.getint(name, 'findtime'),
            'bantime': parser.getint(name, 'bantime'),
            'filter': parser.get(name, 'filter'),
        }
        for name in parser.sections()
    }
